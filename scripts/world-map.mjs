// Writes src/ui/worldLand.ts: the world's land as one SVG path, for the photo lab's map of where you are and where the
// attacker guessed. Natural Earth land at 1:110m (public domain), from the world-atlas package, in an equirectangular
// projection: x = longitude + 180, y = 90 − latitude, one unit per degree (a 360 × 180 box). Run: node scripts/world-map.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/land-110m.json', import.meta.url), 'utf8'));
const land = feature(topo, topo.objects.land);
const round = (n) => Math.round(n * 10) / 10;
const polygons = (g) => (g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : []);
const geometries = land.type === 'FeatureCollection' ? land.features.map((f) => f.geometry) : [land.geometry];

let d = '';
let points = 0;
for (const g of geometries)
  for (const polygon of polygons(g))
    for (const ring of polygon) {
      const xy = [];
      for (const [lon, lat] of ring) {
        const p = `${round(lon + 180)} ${round(90 - lat)}`;
        if (xy[xy.length - 1] !== p) xy.push(p); // points that round to the same place say nothing
      }
      if (xy.length < 4) continue;
      d += `M${xy.join('L')}Z`;
      points += xy.length;
    }

writeFileSync(
  new URL('../src/ui/worldLand.ts', import.meta.url),
  `// Generated by scripts/world-map.mjs: Natural Earth land at 1:110m (public domain), via world-atlas, equirectangular,\n// x = longitude + 180, y = 90 − latitude (a 360 × 180 box). ${points} points.\nexport const LAND = '${d}';\n`,
);
console.log(`src/ui/worldLand.ts: ${points} points, ${d.length} characters`);
